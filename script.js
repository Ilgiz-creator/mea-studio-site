const state = {
  lang: "en",
  occasion: "birthday",
  budget: "60-120 GEL",
  service: ""
};

const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => Array.from(document.querySelectorAll(selector));

function getInitialLang() {
  const saved = localStorage.getItem("mea-lang");
  if (saved && translations[saved]) return saved;
  const browserLang = navigator.language.slice(0, 2);
  if (browserLang === "ka") return "ka";
  if (browserLang === "en") return "en";
  return "en";
}

function applyLanguage(lang) {
  state.lang = lang;
  const dictionary = translations[lang];
  document.documentElement.lang = lang;
  document.title = dictionary.metaTitle;
  const description = document.querySelector("meta[name='description']");
  if (description) description.setAttribute("content", dictionary.metaDescription);

  $$("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) node.textContent = dictionary[key];
  });

  $$("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dictionary[key]) node.setAttribute("placeholder", dictionary[key]);
  });

  $$(".lang-btn").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  localStorage.setItem("mea-lang", lang);
  updateWhatsAppLinks();
}

function selectedLabel(group, value) {
  const dictionary = translations[state.lang];
  if (group === "occasion") return dictionary.occasionValues[value] || value;
  return value;
}

function buildMessage() {
  const dictionary = translations[state.lang];
  const dateValue = $("#order-date")?.value || dictionary.noDate;
  const nameValue = $("#order-name")?.value.trim();
  const commentValue = $("#order-comment")?.value.trim();
  const details = [
    `${dictionary.messageOccasion}: ${selectedLabel("occasion", state.occasion)}`,
    `${dictionary.messageBudget}: ${state.budget}`,
    `${dictionary.messageDate}: ${dateValue}`
  ];
  const extra = [];

  if (state.service) extra.push(`${dictionary.messageService}: ${state.service}`);
  if (nameValue) extra.push(`${dictionary.messageName}: ${nameValue}`);
  if (commentValue) extra.push(`${dictionary.messageComment}: ${commentValue}`);

  const lines = [
    dictionary.messageHello,
    "",
    `${dictionary.messageOrderDetails}:`,
    ...details
  ];

  if (extra.length) {
    lines.push("", `${dictionary.messageAdditionalDetails}:`, ...extra);
  }

  return lines.join("\n");
}

function updateWhatsAppLinks() {
  const message = encodeURIComponent(buildMessage());
  const href = `${WHATSAPP_BASE}?text=${message}`;
  $$("[data-wa-link], #order-whatsapp").forEach((link) => {
    link.setAttribute("href", href);
  });
}

function setChip(group, value) {
  state[group] = value;
  $$(`[data-chip-group="${group}"] .chip`).forEach((chip) => {
    chip.classList.toggle("is-active", chip.dataset.value === value);
  });
  updateWhatsAppLinks();
}

function presetService(serviceKey, budget) {
  const dictionary = translations[state.lang];
  const title = dictionary[`${serviceKey}Title`] || "";
  const occasionByService = {
    cardOne: "romance",
    cardTwo: "other",
    cardThree: "birthday"
  };
  state.service = title;
  setChip("budget", budget);
  setChip("occasion", occasionByService[serviceKey] || "other");
  $("#order-comment").value = title;
  $("#quick-order").scrollIntoView({ behavior: "smooth", block: "center" });
  updateWhatsAppLinks();
}

function init() {
  const today = new Date();
  const yyyy = today.getFullYear();
  const mm = String(today.getMonth() + 1).padStart(2, "0");
  const dd = String(today.getDate()).padStart(2, "0");
  const dateInput = $("#order-date");
  if (dateInput) dateInput.min = `${yyyy}-${mm}-${dd}`;

  $$(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.lang));
  });

  $$("[data-chip-group]").forEach((group) => {
    group.addEventListener("click", (event) => {
      const chip = event.target.closest(".chip");
      if (!chip) return;
      setChip(group.dataset.chipGroup, chip.dataset.value);
    });
  });

  ["#order-date", "#order-name", "#order-comment"].forEach((selector) => {
    const field = $(selector);
    if (field) field.addEventListener("input", updateWhatsAppLinks);
  });

  $$("[data-service]").forEach((button) => {
    button.addEventListener("click", () => presetService(button.dataset.service, button.dataset.budget));
  });

  $$("[data-preset='wedding']").forEach((link) => {
    link.addEventListener("click", () => {
      state.service = translations[state.lang].weddingTitle;
      setChip("occasion", "wedding");
      setChip("budget", "270+ GEL");
    });
  });

  const mapFrame = document.querySelector("[data-map-src]");
  if (mapFrame && "IntersectionObserver" in window) {
    const mapObserver = new IntersectionObserver((entries) => {
      if (!entries.some((entry) => entry.isIntersecting)) return;
      mapFrame.src = mapFrame.dataset.mapSrc;
      mapObserver.disconnect();
    }, { rootMargin: "240px" });
    mapObserver.observe(mapFrame);
  } else if (mapFrame) {
    mapFrame.src = mapFrame.dataset.mapSrc;
  }

  const mobileCta = $(".mobile-cta");
  const orderSection = $(".order-section");
  if (mobileCta && orderSection && "IntersectionObserver" in window) {
    const ctaObserver = new IntersectionObserver((entries) => {
      const orderVisible = entries.some((entry) => entry.isIntersecting);
      mobileCta.classList.toggle("is-hidden", orderVisible);
    }, { threshold: 0.12 });
    ctaObserver.observe(orderSection);
  }

  applyLanguage(getInitialLang());
}

